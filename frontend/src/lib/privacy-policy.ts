/**
 * The privacy policy, as data.
 *
 * The policy has to exist in two places: inside the app, where a user reads it
 * without being thrown out into an external browser, and at the public
 * `/privacy.html` URL that `docs/deploy.md` publishes and checks after a
 * deploy. Keeping two hand-written copies of a legal document invites them to
 * drift, so both are rendered from this module — the app through
 * `PrivacyPolicy.tsx`, the static page through `renderPolicyPage` at build
 * time.
 *
 * Bump `version` and `revised` together whenever the wording below changes.
 */

/** A span of text, optionally emphasised. */
export type PolicyRun = string | { strong: string };

export type PolicyBlock =
  | { kind: "paragraph"; runs: PolicyRun[]; quiet?: boolean }
  | { kind: "list"; items: PolicyRun[][] };

export interface PolicySection {
  heading: string;
  blocks: PolicyBlock[];
}

export interface PolicyDocument {
  title: string;
  eyebrow: string;
  version: string;
  revised: string;
  sections: PolicySection[];
  footer: string;
}

function p(...runs: PolicyRun[]): PolicyBlock {
  return { kind: "paragraph", runs };
}

function quiet(...runs: PolicyRun[]): PolicyBlock {
  return { kind: "paragraph", runs, quiet: true };
}

function list(...items: (PolicyRun[] | string)[]): PolicyBlock {
  return {
    kind: "list",
    items: items.map((item) => (typeof item === "string" ? [item] : item)),
  };
}

