/** Human-readable provenance line shown under the title on both surfaces. */
export function policyMeta(policy: PolicyDocument = PRIVACY_POLICY): string {
  return `Сервис «Похвали себя» (Telegram Mini App) · версия ${policy.version}`
    + ` · редакция от ${policy.revised}`;
}
